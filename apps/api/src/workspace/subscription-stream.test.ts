import { test } from 'node:test';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { ForbiddenException } from '@nestjs/common';
import { PGlite } from '@electric-sql/pglite';
import { MessagingService } from '../messaging/messaging.service';

test('full contact quota retains a single inbound copy and only signals the owning workspace', async () => {
  const pg = new PGlite();
  const tenant = '00000000-0000-4000-8000-000000000001';
  const other = '00000000-0000-4000-8000-000000000002';
  const channelId = '00000000-0000-4000-8000-000000000003';
  try {
    await pg.exec(`
      CREATE ROLE app_user;
      CREATE TABLE tenants(id uuid PRIMARY KEY);
      CREATE TABLE channels(id uuid PRIMARY KEY, tenant_id uuid, type text, status text DEFAULT 'active');
      CREATE TABLE contacts(tenant_id uuid, id uuid DEFAULT gen_random_uuid(), name text, phone text);
      CREATE TABLE messages(channel_id uuid, external_id text, tenant_id uuid, conversation_id uuid,
        direction text,sender_type text,type text,content jsonb,status text,created_at timestamptz,
        id uuid DEFAULT gen_random_uuid(),seq integer GENERATED BY DEFAULT AS IDENTITY);
      CREATE UNIQUE INDEX inbound_key ON messages(channel_id,external_id) WHERE external_id IS NOT NULL;
      CREATE TABLE conversations(id uuid DEFAULT gen_random_uuid(),tenant_id uuid,channel_id uuid,contact_id uuid,
        handled_by text DEFAULT 'bot',status text DEFAULT 'open',last_message_at timestamptz,last_inbound_at timestamptz,unread_count integer DEFAULT 0);
      CREATE UNIQUE INDEX active_dialog ON conversations(channel_id,contact_id) WHERE status<>'closed';
      CREATE TABLE contact_channels(channel_id uuid, external_id text, contact_id uuid, tenant_id uuid, UNIQUE(channel_id,external_id));
      CREATE TABLE subscriptions(tenant_id uuid);
      CREATE TABLE generation_usage(tenant_id uuid, attempts integer);
      CREATE TABLE generation_policy(tenant_id uuid);
      CREATE TABLE realtime_events(tenant_id uuid, payload jsonb);
      INSERT INTO tenants VALUES ('${tenant}'), ('${other}');
      INSERT INTO channels(id,tenant_id,type) VALUES ('${channelId}','${tenant}','web');
      GRANT SELECT ON tenants, channels, contacts, messages, contact_channels TO app_user;
      GRANT UPDATE ON tenants, channels TO app_user;
      GRANT INSERT ON realtime_events TO app_user;
      GRANT SELECT, INSERT, UPDATE, DELETE ON contacts, messages, contact_channels, conversations TO app_user;
      GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO app_user;
    `);
    await pg.exec(
      await readFile(
        join(__dirname, '../database/migrations/120_subscription_usage_stream.sql'),
        'utf8',
      ),
    );
    const db = {
      withTenant: (tenantId: string, run: (c: PGlite) => Promise<unknown>) =>
        pg.transaction(async (c) => {
          await c.exec('SET LOCAL ROLE app_user');
          await c.query("SELECT set_config('app.tenant_id',$1,true)", [tenantId]);
          return run(c as unknown as PGlite);
        }),
    };
    let full = true;
    const messaging = new MessagingService(
      db as never,
      { publish: () => assert.fail('Held inbound must not trigger an automation') } as never,
      {
        assertWithinLimit: () => {
          if (full) throw new ForbiddenException({ code: 'PLAN_LIMIT' });
        },
      } as never,
      {} as never,
      { emit: () => {} } as never,
      {} as never,
      {} as never,
      {} as never,
    );
    const channel = { tenant_id: tenant, id: channelId, type: 'web' } as const;
    const msg = {
      externalMessageId: 'test-1',
      contactExternalId: 'visitor',
      content: { text: 'Test' },
    };
    assert.deepEqual(await messaging.receive(channel as never, msg), {
      held: true,
      duplicate: false,
    });
    assert.deepEqual(await messaging.receive(channel as never, msg), {
      held: true,
      duplicate: true,
    });
    assert.deepEqual((await pg.query('SELECT tenant_id, payload FROM realtime_events')).rows, [
      { tenant_id: tenant, payload: { type: 'usage_changed' } },
    ]);
    assert.equal((await pg.query('SELECT * FROM contacts')).rows.length, 0);
    assert.equal((await pg.query('SELECT * FROM messages')).rows.length, 0);
    assert.equal(
      (
        (await db.withTenant(other, (c) => c.query('SELECT * FROM held_inbound_messages'))) as {
          rows: unknown[];
        }
      ).rows.length,
      0,
    );
    await pg.query('INSERT INTO generation_usage VALUES ($1,1)', [tenant]);
    await pg.query('UPDATE generation_usage SET attempts=2 WHERE tenant_id=$1', [tenant]);
    assert.equal((await pg.query('SELECT * FROM realtime_events')).rows.length, 3);
    await assert.rejects(
      pg.transaction(async (c) => {
        await c.query('UPDATE generation_usage SET attempts=3 WHERE tenant_id=$1', [tenant]);
        throw new Error('rollback');
      }),
      /rollback/,
    );
    assert.equal((await pg.query('SELECT * FROM realtime_events')).rows.length, 3);
    assert.deepEqual(await messaging.restoreHeldInbound(other), { restored: 0 });
    assert.deepEqual(await messaging.restoreHeldInbound(tenant), { restored: 0 });
    full = false;
    assert.deepEqual(await messaging.restoreHeldInbound(tenant), { restored: 1 });
    assert.deepEqual(await messaging.restoreHeldInbound(tenant), { restored: 0 });
    assert.deepEqual((await pg.query('SELECT direction,external_id FROM messages')).rows, [
      { direction: 'in', external_id: 'test-1' },
    ]);
    assert.equal((await pg.query('SELECT * FROM held_inbound_messages')).rows.length, 0);
  } finally {
    await pg.close();
  }
});
